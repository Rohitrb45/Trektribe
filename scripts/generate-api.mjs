import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
const schema = new URL('../api/core.openapi.json', import.meta.url);
const output = new URL('../apps/mobile/src/api/schema.d.ts', import.meta.url);
const text = '// Generated by npm run api:generate. Do not edit.\n' + astToString(await openapiTS(schema, { arrayLength: true }));
if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(() => '');
  if (existing.replace(/\r\n/g, '\n') !== text.replace(/\r\n/g, '\n')) {
    throw new Error('Generated API types are stale. Run npm run api:generate and commit the result.');
  }
} else await writeFile(output, text);